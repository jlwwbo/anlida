export const SLOTS = 20;

// 装载方案：每种板装药先给 2 板备份，装不下就降到 1 板
export function planLoadout(p) {
  const n = p.meds.length;
  const k = Math.max(1, Math.min(3, Math.floor(SLOTS / Math.max(1, n))));
  const used = Math.min(SLOTS, n * k);
  const entries = [];
  let s = 0;
  for (const med of p.meds) {
    for (let b = 0; b < k && s < SLOTS; b++, s++) entries.push({ i: s, med, pack: med.pack, spare: b > 0 });
  }
  // 换板周期：由消耗最快的那种药决定
  let days = Infinity, driver = null;
  for (const med of p.meds) {
    const d = (perBoard(med.pack) * k) / med.per;
    if (d < days) { days = d; driver = med; }
  }
  return { k, used, free: SLOTS - used, entries, days: Math.round(days), driver, n };
}
